"""RQ6 (Phase B): SAFE-ADAPTIVITY as a grid (promoted from prose to a table).

Validates A3: reusing certification labels to CHOOSE the query (post-selection) inflates
the session-level false-certificate rate; a label firewall or sample-split stays valid as
the candidate-predicate family grows.

grid: columns M (candidate predicates) in {10,40,100,500}; rows target recall r in {0.8,0.85,0.9}
methods: unsafe reuse | label firewall | sample-split
metrics: certification rate + SESSION-level false-certificate rate.
Auto-generates its own table.
"""
import json, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from saved.recall_cs import RecallCS

DELTA = 0.10
Ms = [10, 40, 100, 500]
Rs = [0.80, 0.85, 0.90]
METHODS = ["unsafe", "firewall", "split"]


def lower(xs, grid=401):
    cs = RecallCS(delta=DELTA, grid=grid)
    for x in xs:
        cs.update(float(x))
    return cs.lower()


def run(method, R, M, n=90, n_seeds=2000, sigma_pub=0.05):
    false_cert = certified = 0
    for seed in range(n_seeds):
        rng = np.random.default_rng(seed)
        mu = rng.uniform(R - 0.03, R + 0.05, M)         # some below r, some above
        X = (rng.random((M, n)) < mu[:, None]).astype(float)
        if method == "unsafe":
            sel = int(np.argmax(X.mean(1)))
            L = lower(X[sel])
        elif method == "firewall":
            pub = mu + rng.normal(0, sigma_pub, M)      # public signal independent of X
            sel = int(np.argmax(pub))
            L = lower(X[sel])
        else:                                            # split
            h = n // 2
            sel = int(np.argmax(X[:, :h].mean(1)))
            L = lower(X[sel, h:])
        if L >= R:
            certified += 1
            if mu[sel] < R - 1e-9:
                false_cert += 1
    return false_cert / n_seeds, certified / n_seeds


def main():
    out = {"delta": DELTA, "Ms": Ms, "Rs": Rs, "cells": []}
    print(f"\nSAFE-ADAPTIVITY grid (session-level; delta={DELTA})")
    print("cells = certification-rate / SESSION false-cert-rate; dagger = invalid (>delta)")
    for R in Rs:
        print(f"\n r={R}   " + "   ".join(f"M={M}" for M in Ms))
        for m in METHODS:
            cells = []
            for M in Ms:
                fc, cr = run(m, R, M)
                inval = fc > DELTA + 1e-9
                cells.append((round(cr, 3), round(fc, 3), inval))
                out["cells"].append({"R": R, "M": M, "method": m,
                                     "cert_rate": round(cr, 3), "session_false_cert": round(fc, 3),
                                     "invalid": inval})
            print(f"  {m:>9} " + "  ".join(f"{c:.2f}/{f:.2f}{'!' if inv else ' '}" for c, f, inv in cells))
    rp = os.path.join(os.path.dirname(__file__), "..", "results", "safe_adapt_grid.json")
    json.dump(out, open(rp, "w"), indent=1)
    make_table(out)
    print(f"\nsaved -> {os.path.abspath(rp)}")


def make_table(out):
    lab = {"unsafe": "unsafe reuse", "firewall": "label firewall", "split": "sample-split"}
    d = {(c["R"], c["method"], c["M"]): c for c in out["cells"]}
    lines = ["% AUTO-GENERATED by experiments/exp_safe_adapt_grid.py",
             "% cells: certification-rate / SESSION-level false-cert-rate; $\\dagger$=invalid ($>\\delta$).",
             "\\begin{tabular}{ll" + "c" * len(Ms) + "}", "\\toprule",
             "$r$ & method & " + " & ".join(f"$M{{=}}{M}$" for M in Ms) + " \\\\", "\\midrule"]
    for R in Rs:
        for i, m in enumerate(METHODS):
            cells = []
            for M in Ms:
                c = d[(R, m, M)]
                s = f"{c['cert_rate']:.2f}/{c['session_false_cert']:.2f}"
                if c["invalid"]:
                    s = f"{c['cert_rate']:.2f}/\\textbf{{{c['session_false_cert']:.2f}}}$^\\dagger$"
                cells.append(s)
            rlab = f"{R:.2f}" if i == 0 else ""
            lines.append(f"{rlab} & {lab[m]} & " + " & ".join(cells) + " \\\\")
        if R != Rs[-1]:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}"]
    tp = os.path.join(os.path.dirname(__file__), "..", "figures", "table_safe_adapt.tex")
    open(tp, "w").write("\n".join(lines) + "\n")
    print(f"table -> {os.path.abspath(tp)}")


if __name__ == "__main__":
    main()
