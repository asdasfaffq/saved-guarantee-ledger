"""RQ6 (Phase B): PREVALENCE / oracle-call accounting. Is the label cost understated?

The recall identity conditions on oracle-labelled POSITIVES. Finding one positive costs
~1/prevalence oracle calls (you label records until one is a positive). This experiment
makes the FULL oracle-call ledger explicit so label cost cannot look understated.

x = prevalence pi in {0.01,0.05,0.1,0.2,0.5}
For a session that needs `pos_needed` positive labels to certify (fresh, per-query budget),
report per certificate:
  total oracle calls, positive labels, negative-rejected labels, reused labels (free),
  human-anchor labels, and total oracle calls PER CERTIFICATE.

We use SAVED's actual certify loop (per-sample shift) to measure how many fresh POSITIVE
labels it consumes to certify, then convert to total oracle calls via the geometric
sampling cost 1/pi. reused labels are counted (free -- already paid in a prior query).
Auto-generates its own table (self-generating so make_figures cannot overwrite it).
"""
import json, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from saved.recall_cs import RecallCS
from saved.baselines import PHI_MAX
from saved.drift import true_recall

GRID, TAU, MU0, R, DELTA, ANCHOR = 401, 0.5, 1.6, 0.80, 0.10, 5
EPS, ELL, B = 0.4, 0.7, 200      # allow a large budget so certificates actually happen


def certify(reuse, fresh, t_now, kappa):
    cs = RecallCS(delta=DELTA, grid=GRID)
    for (x, ti) in reuse:
        cs.update_shift(x, 1.0, kappa * max(0.0, t_now - ti))
    used = 0
    while cs.lower() < R and used < len(fresh):
        cs.update(fresh[used]); used += 1
    return cs.lower() >= R, used


def run(pi, n_seeds=120, N=25):
    kappa = EPS * PHI_MAX
    tot_cert = 0
    led = {"pos": 0, "neg": 0, "reused": 0, "anchor": 0}   # per-certificate accumulators
    for seed in range(n_seeds):
        rng = np.random.default_rng(seed)
        pool = []
        for q in range(N):
            t = q / (N - 1)
            r_now = true_recall(t, TAU, MU0, EPS)
            fresh = (rng.random(B) < r_now).astype(float)
            applicable = [p for p in pool if rng.random() < ELL]
            cert, used_pos = certify(applicable, fresh, t, kappa)
            if cert:
                tot_cert += 1
                # geometric sampling: each fresh positive label costs ~1/pi oracle calls;
                # the (1/pi - 1) others per positive are negative-rejected labels.
                led["pos"] += used_pos
                led["neg"] += used_pos * (1.0 / pi - 1.0)
                led["reused"] += len(applicable)
                led["anchor"] += ANCHOR
            for x in fresh:
                pool.append((float(x), t))
    if tot_cert == 0:
        return None
    pos = led["pos"] / tot_cert
    neg = led["neg"] / tot_cert
    reused = led["reused"] / tot_cert
    anchor = led["anchor"] / tot_cert
    total_oracle = pos + neg + anchor         # reused labels are FREE (already paid)
    return {"pos": pos, "neg": neg, "reused": reused, "anchor": anchor,
            "total_oracle_per_cert": total_oracle}


def main():
    pis = [0.01, 0.05, 0.1, 0.2, 0.5]
    out = {"eps": EPS, "ell": ELL, "R": R, "rows": []}
    print(f"\nPREVALENCE / oracle-call accounting (eps={EPS}, target={R})")
    print(f"{'pi':>6} | {'total/cert':>10} | {'pos':>7} {'neg-rej':>8} {'reused':>7} {'anchor':>7}")
    rows_tex = []
    for pi in pis:
        r = run(pi)
        if r is None:
            print(f"{pi:>6} | (no certificates at this budget)"); continue
        print(f"{pi:>6} | {r['total_oracle_per_cert']:>10.1f} | {r['pos']:>7.1f} {r['neg']:>8.1f} "
              f"{r['reused']:>7.1f} {r['anchor']:>7.1f}")
        out["rows"].append({"pi": pi, **{k: round(v, 2) for k, v in r.items()}})
        rows_tex.append(f"{pi:.2f} & {r['total_oracle_per_cert']:.0f} & {r['pos']:.0f} & "
                        f"{r['neg']:.0f} & {r['reused']:.0f} & {r['anchor']:.0f} \\\\")
    rp = os.path.join(os.path.dirname(__file__), "..", "results", "prevalence.json")
    json.dump(out, open(rp, "w"), indent=1)
    tex = ("% AUTO-GENERATED by experiments/exp_prevalence.py\n"
           "\\begin{tabular}{cccccc}\n\\toprule\n"
           "$\\pi$ & total/cert & pos & neg-rej & reused & anchor \\\\\n\\midrule\n"
           + "\n".join(rows_tex) + "\n\\bottomrule\n\\end{tabular}\n")
    tp = os.path.join(os.path.dirname(__file__), "..", "figures", "table_prevalence.tex")
    open(tp, "w").write(tex)
    print(f"\nsaved -> {os.path.abspath(rp)}\ntable -> {os.path.abspath(tp)}")


if __name__ == "__main__":
    main()
