"""Session-level version of the valid-baselines comparison (main-agent verification).

The shipped valid_baselines.py reports a PER-QUERY false-cert rate, but the paper's
validity thesis is SESSION-level (FWER): a method is trustworthy iff P(>=1 false
certificate in a session) <= delta. This recomputes the same methods at that level,
so we can see whether recent-window/fresh-only are actually VALID at the paper's own
criterion (they may look fine per-query but compound over a session).
"""
import sys, os
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from saved.drift import true_recall
from saved.baselines import PHI_MAX
from experiments.valid_baselines import certify, TAU, MU0, R, B, DELTA

def run_session(eps, methods, N=25, n_seeds=150):
    kappa = eps * PHI_MAX
    agg = {m: {"true": 0, "cert": 0, "bad_session": 0} for m in methods}
    for seed in range(n_seeds):
        rng = np.random.default_rng(seed)
        pool = []
        sess_false = {m: False for m in methods}
        for q in range(N):
            t = q / (N - 1)
            r_now = true_recall(t, TAU, MU0, eps)
            good = r_now >= R - 1e-9
            fresh = (rng.random(B) < r_now).astype(float)
            for m in methods:
                cert, _ = certify(pool, fresh, t, kappa, m)
                if cert:
                    agg[m]["cert"] += 1
                    if good:
                        agg[m]["true"] += 1
                    else:
                        sess_false[m] = True
            for x in fresh:
                pool.append((float(x), t))
        for m in methods:
            if sess_false[m]:
                agg[m]["bad_session"] += 1
    tot = N * n_seeds
    return {m: {"trusted_yield": agg[m]["true"]/tot,
                "session_false_rate": agg[m]["bad_session"]/n_seeds} for m in methods}

def main():
    methods = ["saved", "fresh", "recent", "maxage"]
    print(f"\nSESSION-LEVEL valid-baselines (delta={DELTA}, target={R}, N=25 queries/session, 400 sessions)")
    print("VALID (session) := session_false_rate <= delta. Trusted yield = certified-and-true / query-instances.\n")
    hdr = f"{'eps':>4} | " + " | ".join(f"{m:>22}" for m in ["saved","fresh-only","recent-window","max-age"])
    print(hdr); print("-"*len(hdr))
    res = {}
    for eps in [0.0, 0.4, 0.8]:
        r = run_session(eps, methods)
        res[eps] = r
        row = f"{eps:>4} | "
        cells = []
        for m in methods:
            valid = "V" if r[m]["session_false_rate"] <= DELTA else "INVALID"
            cells.append(f"yld{r[m]['trusted_yield']:.2f} sFC{r[m]['session_false_rate']:.2f}[{valid}]".rjust(22))
        print(row + " | ".join(cells))
    print("\n(sFC = session-level false-cert rate; must be <= delta=0.1 to be a VALID comparator)")

    # Emit the paper table (trusted yield / session-level false-cert; dagger = invalid at FWER level).
    labels = {"fresh": "fresh-only (no reuse)", "recent": "recent-window (no shift)",
              "maxage": "max-age (conservative)", "saved": r"\textbf{SAVED (per-sample)}"}
    order = ["fresh", "recent", "maxage", "saved"]
    # Bold the best yield only among methods that are session-VALID at that drift level.
    best_yld = {e: max((res[e][m]["trusted_yield"] for m in methods
                        if res[e][m]["session_false_rate"] <= DELTA), default=0.0) for e in res}
    lines = [r"% AUTO-GENERATED by experiments/valid_baselines_session.py (150 sessions, N=25).",
             r"% Cells: trusted yield / SESSION-level false-certificate rate. Valid iff sFC <= delta=0.1.",
             r"\begin{tabular}{lccc}", r"\toprule",
             r"method (all aim to be valid) & $\epsilon{=}0.0$ & $\epsilon{=}0.4$ & $\epsilon{=}0.8$ \\",
             r"\midrule"]
    for m in order:
        cells = []
        for e in [0.0, 0.4, 0.8]:
            y, s = res[e][m]["trusted_yield"], res[e][m]["session_false_rate"]
            ytxt = rf"\textbf{{{y:.2f}}}" if abs(y - best_yld[e]) < 1e-9 else f"{y:.2f}"
            stxt = rf"\textbf{{{s:.2f}}}$^{{\dagger}}$" if s > DELTA + 1e-9 else f"{s:.2f}"
            cells.append(f"{ytxt} / {stxt}")
        lines.append(f"{labels[m]:<26}& " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", "",
              r"{\scriptsize $^{\dagger}$ session false-cert rate ${>}\delta{=}0.1$: \emph{invalid} at the session (FWER) level.}"]
    tp = os.path.join(os.path.dirname(__file__), "..", "figures", "table_valid.tex")
    open(tp, "w").write("\n".join(lines) + "\n")
    print(f"table -> {os.path.abspath(tp)}")

if __name__ == "__main__":
    main()
